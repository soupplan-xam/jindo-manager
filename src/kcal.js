// ---- 24절기 ----
const TERMS = ['소한', '대한', '입춘', '우수', '경칩', '춘분', '청명', '곡우', '입하', '소만', '망종', '하지',
  '소서', '대서', '입추', '처서', '백로', '추분', '한로', '상강', '입동', '소설', '대설', '동지']
const rad = d => (d * Math.PI) / 180

// 겉보기 태양 황경(도). Meeus 저정밀식.
function sunLongitude(ms) {
  const jde = ms / 86400000 + 2440587.5 + 69 / 86400
  const T = (jde - 2451545) / 36525
  const L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T * T
  const M = rad(357.52911 + 35999.05029 * T - 0.0001537 * T * T)
  const C = (1.914602 - 0.004817 * T - 0.000014 * T * T) * Math.sin(M) + (0.019993 - 0.000101 * T) * Math.sin(2 * M) + 0.000289 * Math.sin(3 * M)
  const om = rad(125.04 - 1934.136 * T)
  const lam = L0 + C - 0.00569 - 0.00478 * Math.sin(om)
  return ((lam % 360) + 360) % 360
}

const cache = new Map()
// 그 해의 절기 → Map(iso → 이름). 날짜는 한국 시간 기준.
export function solarTerms(year) {
  if (cache.has(year)) return cache.get(year)
  const out = new Map()
  TERMS.forEach((name, k) => {
    const target = (285 + 15 * k) % 360
    let ms = Date.UTC(year, 0, 6) + k * 15.2184 * 86400000
    for (let i = 0; i < 8; i++) {
      let diff = target - sunLongitude(ms)
      diff = ((diff + 540) % 360) - 180
      ms += (diff / 360) * 365.2422 * 86400000
    }
    const kst = new Date(ms + 9 * 3600000)
    const iso = kst.getUTCFullYear() + '-' + String(kst.getUTCMonth() + 1).padStart(2, '0') + '-' + String(kst.getUTCDate()).padStart(2, '0')
    out.set(iso, name)
  })
  cache.set(year, out)
  return out
}
export const solarTermOn = iso => solarTerms(Number(iso.slice(0, 4))).get(iso) || null
